import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = process.cwd();
const outputPath = path.join(repositoryRoot, "public", "service-worker.js");

function sha256File(absolutePath) {
  return createHash("sha256").update(readFileSync(absolutePath)).digest("hex");
}

function routeFromAppManifestKey(key) {
  if (!key.endsWith("/page")) return null;
  const route = key === "/page" ? "/" : key.slice(0, -"/page".length);
  return route === "/devtools" ? null : route;
}

export function deriveServiceWorkerBuildId({
  sourceBuildId,
  essentialAssets,
  routes,
  assetIntegrity,
}) {
  const canonicalManifest = JSON.stringify({
    sourceBuildId,
    essentialAssets: essentialAssets.slice().sort(),
    routes: routes.slice().sort(),
    assetIntegrity: Object.fromEntries(
      Object.entries(assetIntegrity).sort(([leftPath], [rightPath]) =>
        leftPath.localeCompare(rightPath),
      ),
    ),
  });
  const manifestDigest = createHash("sha256").update(canonicalManifest).digest("hex").slice(0, 12);

  return `${sourceBuildId}-${manifestDigest}`;
}

export function collectServiceWorkerBuildManifest(rootPath = repositoryRoot) {
  const sourceBuildId = readFileSync(path.join(rootPath, ".next", "BUILD_ID"), "utf8").trim();
  if (!/^[a-z0-9_-]{6,80}$/i.test(sourceBuildId)) throw new Error("The Next.js build ID is invalid.");

  const appBuildManifest = JSON.parse(
    readFileSync(path.join(rootPath, ".next", "app-build-manifest.json"), "utf8"),
  );
  const appPathsManifest = JSON.parse(
    readFileSync(path.join(rootPath, ".next", "server", "app-paths-manifest.json"), "utf8"),
  );
  const buildManifest = JSON.parse(
    readFileSync(path.join(rootPath, ".next", "build-manifest.json"), "utf8"),
  );

  const nextAssetPaths = new Set([
    ...(buildManifest.rootMainFiles ?? []),
    ...Object.values(buildManifest.pages ?? {}).flat(),
    ...Object.entries(appBuildManifest.pages ?? {})
      .filter(([manifestKey]) => manifestKey !== "/devtools/page")
      .flatMap(([, assetPaths]) => assetPaths),
  ]);
  const assetIntegrity = {};
  const essentialAssets = [];

  for (const assetPath of Array.from(nextAssetPaths).sort()) {
    if (!assetPath.startsWith("static/") || assetPath.includes(".map")) continue;
    const absolutePath = path.join(rootPath, ".next", assetPath);
    if (!existsSync(absolutePath)) throw new Error(`Manifest asset is missing: ${assetPath}`);
    const urlPath = `/_next/${assetPath}`;
    essentialAssets.push(urlPath);
    assetIntegrity[urlPath] = sha256File(absolutePath);
  }

  for (const publicPath of ["/content-packs/manifest.json"]) {
    const absolutePath = path.join(rootPath, "public", publicPath.slice(1));
    if (!existsSync(absolutePath)) throw new Error(`Required public asset is missing: ${publicPath}`);
    essentialAssets.push(publicPath);
    assetIntegrity[publicPath] = sha256File(absolutePath);
  }

  const contentManifest = JSON.parse(
    readFileSync(path.join(rootPath, "public", "content-packs", "manifest.json"), "utf8"),
  );
  for (const entry of contentManifest.packs ?? []) {
    if (typeof entry.path !== "string" || !entry.path.startsWith("/content-packs/packs/")) continue;
    const absolutePath = path.join(rootPath, "public", entry.path.slice(1));
    if (existsSync(absolutePath)) assetIntegrity[entry.path] = sha256File(absolutePath);
  }

  const routes = Array.from(
    new Set([
      ...Object.keys(appPathsManifest).map(routeFromAppManifestKey).filter(Boolean),
      "/icon.svg",
      "/manifest.webmanifest",
    ]),
  ).sort();
  if (!routes.includes("/offline")) throw new Error("The production build has no offline fallback route.");

  const buildId = deriveServiceWorkerBuildId({
    sourceBuildId,
    essentialAssets,
    routes,
    assetIntegrity,
  });

  return { buildId, essentialAssets, routes, assetIntegrity };
}

export function renderServiceWorker(manifest) {
  return `/* This file is generated by scripts/generate-service-worker.mjs. */
const CACHE_PREFIX = "nullkeys-build";
const BUILD_ID = ${JSON.stringify(manifest.buildId)};
const CACHE_NAME = \`\${CACHE_PREFIX}-\${BUILD_ID}\`;
const ESSENTIAL_ASSETS = ${JSON.stringify(manifest.essentialAssets, null, 2)};
const APP_ROUTES = ${JSON.stringify(manifest.routes, null, 2)};
const ASSET_INTEGRITY = Object.freeze(${JSON.stringify(manifest.assetIntegrity, null, 2)});
const pendingActivationRequests = new Map();

function requestPath(request) {
  return new URL(request.url, self.location.origin).pathname;
}

function isSameOriginRequest(request) {
  const requestUrl = new URL(request.url, self.location.origin);
  return requestUrl.origin === self.location.origin && (requestUrl.protocol === "http:" || requestUrl.protocol === "https:");
}

function isCacheableResponse(response) {
  return response.ok && (response.type === "basic" || response.type === "default") && !/\\bno-store\\b/i.test(response.headers.get("Cache-Control") || "");
}

async function responseMatchesIntegrity(pathname, response) {
  const expectedDigest = ASSET_INTEGRITY[pathname];
  if (!expectedDigest) return true;
  try {
    const payload = await response.clone().arrayBuffer();
    const digest = await crypto.subtle.digest("SHA-256", payload);
    const actualDigest = Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
    return actualDigest === expectedDigest;
  } catch {
    return false;
  }
}

async function fetchVerified(request) {
  const response = await fetch(request, { cache: "no-store" });
  if (!isCacheableResponse(response) || !(await responseMatchesIntegrity(requestPath(request), response))) {
    throw new Error("The fetched asset failed cache validation.");
  }
  return response;
}

async function readVerifiedCache(cache, request, options) {
  const cached = await cache.match(request, options);
  if (!cached) return null;
  if (await responseMatchesIntegrity(requestPath(request), cached)) return cached;
  await cache.delete(request, options);
  return null;
}

async function installBuild() {
  const cache = await caches.open(CACHE_NAME);
  for (const assetPath of ESSENTIAL_ASSETS) {
    const request = new Request(new URL(assetPath, self.location.origin), { cache: "reload", credentials: "same-origin" });
    const response = await fetchVerified(request);
    await cache.put(request, response.clone());
  }
  for (const routePath of APP_ROUTES) {
    try {
      const request = new Request(new URL(routePath, self.location.origin), { cache: "reload", credentials: "same-origin" });
      const response = await fetchVerified(request);
      await cache.put(request, response.clone());
    } catch {
      if (routePath === "/offline") throw new Error("The offline fallback could not be cached.");
    }
  }
}

async function respondToNavigation(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    return await fetch(request);
  } catch {
    return (await readVerifiedCache(cache, request, { ignoreSearch: true })) ||
      (await readVerifiedCache(cache, "/offline")) || Response.error();
  }
}

async function respondToAsset(request) {
  const cache = await caches.open(CACHE_NAME);
  const pathname = requestPath(request);
  if (!Object.hasOwn(ASSET_INTEGRITY, pathname)) {
    try {
      return await fetch(request, { cache: "no-store" });
    } catch {
      return Response.error();
    }
  }
  const cached = await readVerifiedCache(cache, request, { ignoreSearch: false });
  if (cached) return cached;
  try {
    const response = await fetchVerified(request);
    await cache.put(request, response.clone());
    return response;
  } catch {
    return Response.error();
  }
}

async function coordinateActivation() {
  const clients = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  if (clients.length === 0) {
    await self.skipWaiting();
    return;
  }
  const requestId = \`\${BUILD_ID}:\${Date.now()}:\${Math.random()}\`;
  const requestState = { expected: new Set(clients.map((client) => client.id)), active: false };
  pendingActivationRequests.set(requestId, requestState);
  for (const client of clients) client.postMessage({ type: "NULLKEYS_PREPARE_UPDATE", requestId });
  await new Promise((resolve) => setTimeout(resolve, 750));
  pendingActivationRequests.delete(requestId);
  if (requestState.active || requestState.expected.size > 0) {
    for (const client of clients) client.postMessage({ type: "NULLKEYS_UPDATE_BLOCKED" });
    return;
  }
  await self.skipWaiting();
}

self.addEventListener("install", (event) => {
  event.waitUntil(installBuild());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME).map((key) => caches.delete(key)));
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  const message = event.data;
  if (message?.type === "NULLKEYS_ACTIVATE_UPDATE") {
    event.waitUntil(coordinateActivation());
    return;
  }
  if (message?.type === "NULLKEYS_UPDATE_CLIENT_STATE" && message.requestId) {
    const requestState = pendingActivationRequests.get(message.requestId);
    if (!requestState || !event.source?.id) return;
    requestState.expected.delete(event.source.id);
    requestState.active ||= message.activeTypingSession === true;
  }
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET" || !isSameOriginRequest(event.request)) return;
  if (event.request.mode === "navigate") {
    event.respondWith(respondToNavigation(event.request));
    return;
  }
  const pathname = requestPath(event.request);
  if (
    pathname.startsWith("/_next/static/") ||
    pathname.startsWith("/content-packs/") ||
    Object.hasOwn(ASSET_INTEGRITY, pathname) ||
    event.request.destination === "font" ||
    event.request.destination === "image" ||
    event.request.destination === "script" ||
    event.request.destination === "style"
  ) event.respondWith(respondToAsset(event.request));
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const manifest = collectServiceWorkerBuildManifest(repositoryRoot);
  writeFileSync(outputPath, renderServiceWorker(manifest));
  process.stdout.write(`Generated ${path.relative(repositoryRoot, outputPath)} for build ${manifest.buildId} with ${manifest.essentialAssets.length} assets and ${manifest.routes.length} routes.\n`);
}
